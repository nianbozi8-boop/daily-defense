/**
 * Deterministically retrieves today's primary Catholic quote of the day
 * based on the calendar year and day of the year.
 */
export function getTodaySpotlightQuote(targetDate: Date = new Date()): DailyCatholicQuote {
  const startOfYear = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const deterministicSeed = targetDate.getFullYear() * 366 + dayOfYear;
  const index = Math.abs(deterministicSeed) % DAILY_CATHOLIC_QUOTES.length;
  return DAILY_CATHOLIC_QUOTES[index];
}

/**
 * Deterministically retrieves today's 3 distinct Catholic pillars:
 * 1. Church Father of the Day
 * 2. Catholic Scientist of the Day
 * 3. Apologetics Titan of the Day
 */
export function getTodayPillars(targetDate: Date = new Date()): {
  father: DailyCatholicQuote;
  scientist: DailyCatholicQuote;
  apologist: DailyCatholicQuote;
} {
  const startOfYear = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));

  const fathers = DAILY_CATHOLIC_QUOTES.filter((q) => q.category === "church_father");
  const scientists = DAILY_CATHOLIC_QUOTES.filter((q) => q.category === "catholic_scientist");
  const apologists = DAILY_CATHOLIC_QUOTES.filter((q) => q.category === "apologetic_titan");

  const fatherSeed = targetDate.getFullYear() * 366 + dayOfYear + 19;
  const sciSeed = targetDate.getFullYear() * 366 + dayOfYear + 7;
  const apoSeed = targetDate.getFullYear() * 366 + dayOfYear + 31;

  return {
    father: fathers[Math.abs(fatherSeed) % fathers.length],
    scientist: scientists[Math.abs(sciSeed) % scientists.length],
    apologist: apologists[Math.abs(apoSeed) % apologists.length],
  };
}
